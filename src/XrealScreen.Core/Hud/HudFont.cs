namespace XrealScreen.Core.Hud;

/// <summary>
/// A 5×7 bitmap font for the HUD readouts. Each glyph is seven rows, five bits per row, bit 4 on the left.
/// Only the characters the HUD prints are defined; anything else is blank.
/// </summary>
public static class HudFont
{
    public const int Columns = 5;
    public const int Rows = 7;

    private static readonly Dictionary<char, byte[]> Glyphs = new()
    {
        ['0'] = [0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E],
        ['1'] = [0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E],
        ['2'] = [0x0E, 0x11, 0x01, 0x06, 0x08, 0x10, 0x1F],
        ['3'] = [0x0E, 0x11, 0x01, 0x06, 0x01, 0x11, 0x0E],
        ['4'] = [0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02],
        ['5'] = [0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E],
        ['6'] = [0x0E, 0x10, 0x10, 0x1E, 0x11, 0x11, 0x0E],
        ['7'] = [0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08],
        ['8'] = [0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E],
        ['9'] = [0x0E, 0x11, 0x11, 0x0F, 0x01, 0x01, 0x0E],
        ['D'] = [0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E],
        ['G'] = [0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0E],
        ['H'] = [0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
        ['P'] = [0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10],
        ['R'] = [0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11],
        ['A'] = [0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
        ['B'] = [0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E],
        ['C'] = [0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E],
        ['E'] = [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F],
        ['F'] = [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10],
        ['I'] = [0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E],
        ['K'] = [0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11],
        ['L'] = [0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F],
        ['M'] = [0x11, 0x1B, 0x15, 0x11, 0x11, 0x11, 0x11],
        ['N'] = [0x11, 0x19, 0x15, 0x13, 0x11, 0x11, 0x11],
        ['O'] = [0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
        ['S'] = [0x0E, 0x11, 0x10, 0x0E, 0x01, 0x11, 0x0E],
        ['T'] = [0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04],
        ['U'] = [0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
        ['V'] = [0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04],
        ['W'] = [0x11, 0x11, 0x11, 0x15, 0x15, 0x1B, 0x11],
        ['Y'] = [0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04],
        ['+'] = [0x00, 0x04, 0x04, 0x1F, 0x04, 0x04, 0x00],
        ['-'] = [0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00],
        ['.'] = [0x00, 0x00, 0x00, 0x00, 0x00, 0x04, 0x04],
        [':'] = [0x00, 0x04, 0x00, 0x00, 0x04, 0x00, 0x00],
        [' '] = [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00],
    };

    public static bool Ink(char character, int column, int row)
    {
        if (column < 0 || column >= Columns || row < 0 || row >= Rows)
        {
            return false;
        }

        if (!Glyphs.TryGetValue(char.ToUpperInvariant(character), out byte[]? rows))
        {
            return false;
        }

        return (rows[row] & (1 << (Columns - 1 - column))) != 0;
    }

    /// <summary>True when the HUD can draw this character.</summary>
    public static bool Knows(char character) => Glyphs.ContainsKey(char.ToUpperInvariant(character));
}
